// Get all published products
export const getPublishedProducts = () =>
  products.filter((product) => product.status === "published");

// Get featured products
export const getFeaturedProducts = () =>
  getPublishedProducts().filter((product) => product.isFeatured);

// Find a product using its URL slug
export const getProductBySlug = (slug: string) =>
  getPublishedProducts().find((product) => product.slug === slug);

// Get products by category
export const getProductsByCategory = (category: string) =>
  getPublishedProducts().filter(
    (product) => product.category === category
  );

// Search products
export const searchProducts = (query: string) => {
  const normalizedQuery = query.toLowerCase().trim();

  if (!normalizedQuery) return getPublishedProducts();

  return getPublishedProducts().filter((product) => {
    const searchableContent = [
      product.name,
      product.brand ?? "",
      product.category,
      product.description,
      ...(product.features ?? []),
    ]
      .join(" ")
      .toLowerCase();

    return searchableContent.includes(normalizedQuery);
  });
};
